import Carbon.HIToolbox

/// Translates the virtual key codes of macOS into the scancodes the emulator's display server expects.
///
/// Keys are sent by position, as XT set 1 scancodes, rather than by the character they produce: the
/// guest then applies its own keyboard layout, and keys that produce no character (function keys,
/// modifiers, arrows) need no special treatment. Keys that the XT set reaches through an `E0` prefix
/// carry `0x80` instead, which is the encoding of the extended key event.
enum QEMUKeyMap {

    /// The virtual key code of the caps lock key, which macOS reports once per physical press.
    static let capsLockKeyCode: UInt16 = 0x39

    /// The scancode of each virtual key code that has one.
    private static let scancodes: [UInt16: UInt16] = [
        0x00: 0x1E, 0x01: 0x1F, 0x02: 0x20, 0x03: 0x21, 0x04: 0x23, 0x05: 0x22, 0x06: 0x2C, 0x07: 0x2D,
        0x08: 0x2E, 0x09: 0x2F, 0x0A: 0x56, 0x0B: 0x30, 0x0C: 0x10, 0x0D: 0x11, 0x0E: 0x12, 0x0F: 0x13,
        0x10: 0x15, 0x11: 0x14, 0x12: 0x02, 0x13: 0x03, 0x14: 0x04, 0x15: 0x05, 0x16: 0x07, 0x17: 0x06,
        0x18: 0x0D, 0x19: 0x0A, 0x1A: 0x08, 0x1B: 0x0C, 0x1C: 0x09, 0x1D: 0x0B, 0x1E: 0x1B, 0x1F: 0x18,
        0x20: 0x16, 0x21: 0x1A, 0x22: 0x17, 0x23: 0x19, 0x24: 0x1C, 0x25: 0x26, 0x26: 0x24, 0x27: 0x28,
        0x28: 0x25, 0x29: 0x27, 0x2A: 0x2B, 0x2B: 0x33, 0x2C: 0x35, 0x2D: 0x31, 0x2E: 0x32, 0x2F: 0x34,
        0x30: 0x0F, 0x31: 0x39, 0x32: 0x29, 0x33: 0x0E, 0x35: 0x01, 0x36: 0xDC, 0x37: 0xDB, 0x38: 0x2A,
        0x39: 0x3A, 0x3A: 0x38, 0x3B: 0x1D, 0x3C: 0x36, 0x3D: 0xB8, 0x3E: 0x9D, 0x41: 0x53, 0x43: 0x37,
        0x45: 0x4E, 0x47: 0x45, 0x4B: 0xB5, 0x4C: 0x9C, 0x4E: 0x4A, 0x52: 0x52, 0x53: 0x4F, 0x54: 0x50,
        0x55: 0x51, 0x56: 0x4B, 0x57: 0x4C, 0x58: 0x4D, 0x59: 0x47, 0x5B: 0x48, 0x5C: 0x49, 0x60: 0x3F,
        0x61: 0x40, 0x62: 0x41, 0x63: 0x3D, 0x64: 0x42, 0x65: 0x43, 0x67: 0x57, 0x69: 0xB7, 0x6B: 0x46,
        0x6D: 0x44, 0x6F: 0x58, 0x72: 0xD2, 0x73: 0xC7, 0x74: 0xC9, 0x75: 0xD3, 0x76: 0x3E, 0x77: 0xCF,
        0x78: 0x3C, 0x79: 0xD1, 0x7A: 0x3B, 0x7B: 0xCB, 0x7C: 0xCD, 0x7D: 0xD0, 0x7E: 0xC8
    ]

    /// The two keys whose codes ISO keyboards report swapped: the key left of `1` and the key right
    /// of the left shift key.
    private static let isoSwappedKeyCodes: (UInt16, UInt16) = (0x0A, 0x32)

    /// Returns the scancode of a key.
    ///
    /// - Parameters:
    ///   - keyCode: The virtual key code reported by AppKit.
    ///   - isISOKeyboard: Whether the key comes from a keyboard with the ISO layout.
    /// - Returns: The scancode, or `nil` for keys the guest cannot receive.
    static func scancode(for keyCode: UInt16, isISOKeyboard: Bool) -> UInt16? {

        var keyCode = keyCode

        if isISOKeyboard {
            switch keyCode {
            case isoSwappedKeyCodes.0: keyCode = isoSwappedKeyCodes.1
            case isoSwappedKeyCodes.1: keyCode = isoSwappedKeyCodes.0
            default: break
            }
        }

        return scancodes[keyCode]
    }

    /// Whether the keyboard in use has the ISO physical layout.
    ///
    /// - Note: Reads the type of the keyboard that sent the most recent event.
    @MainActor
    static var isISOKeyboard: Bool {
        Int(KBGetLayoutType(Int16(LMGetKbdType()))) == Int(kKeyboardISO)
    }
}
